import express from "express";
import auth from "../middleware/auth.js";
import { getPlans, getMySubscription, createOrder, verifyOrder, getInvoice } from "../controller/subscription.js";
const router = express.Router();
router.get("/plans", getPlans);
router.get("/me", auth, getMySubscription);
router.post("/create-order", auth, createOrder);
router.post("/verify", auth, verifyOrder);
router.get("/invoice/:paymentId", auth, getInvoice);
export default router;
