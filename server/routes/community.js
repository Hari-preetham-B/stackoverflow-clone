import express from "express";
import auth from "../middleware/auth.js";
import admin from "../middleware/admin.js";
import { createPost, getFeed, getTrending, getExclusiveFeed, updatePost, deletePost, likePost, commentPost, replyComment, sharePost, bookmarkPost, followUser, reportPost, getNotifications, moderatePost } from "../controller/community.js";
const router = express.Router();
router.get("/feed", auth, getFeed);
router.get("/trending", auth, getTrending);
router.get("/exclusive", auth, getExclusiveFeed);
router.get("/notifications", auth, getNotifications);
router.post("/posts", auth, createPost);
router.patch("/posts/:id", auth, updatePost);
router.delete("/posts/:id", auth, deletePost);
router.post("/posts/:id/like", auth, likePost);
router.post("/posts/:id/comments", auth, commentPost);
router.post("/posts/:id/comments/:commentId/replies", auth, replyComment);
router.post("/posts/:id/share", auth, sharePost);
router.post("/posts/:id/bookmark", auth, bookmarkPost);
router.post("/users/:userId/follow", auth, followUser);
router.post("/posts/:id/report", auth, reportPost);
router.patch("/admin/posts/:id/moderate", auth, admin, moderatePost);
export default router;
